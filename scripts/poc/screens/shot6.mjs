import { chromium } from "playwright-core";
const [url, outDir] = process.argv.slice(2);
const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--use-angle=metal", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
const logs = [];
page.on("pageerror", (e) => logs.push(`pageerror: ${e.message}`));
page.on("console", (m) => { if (m.type() === "error") logs.push(m.text()); });
await page.goto(url);
await page.waitForSelector(".route-legend", { timeout: 30000 });
console.log("legend:", (await page.textContent(".route-legend")).replace(/\s+/g, " "));
const go = (a) => page.evaluate(([lat, lon, h, az, el]) => window.mars.placeCamera({ lat, lon, height: h }, az, el), a);
const settle = async (a) => { await go(a); await page.waitForTimeout(14000); await go(a); await page.waitForTimeout(1500); };
await settle([18.4250, 77.4454, -4250 + 1300, 0, -42]);
await page.screenshot({ path: `${outDir}/16_route_overview.png` });
await page.evaluate(() => window.streetView.walk({ lat: 18.4410, lon: 77.4480, height: -4250 }));
await page.evaluate(() => { const f = window.mars.firstPerson; f.az = 215; f.el = -12; });
await page.waitForTimeout(12000);
await page.screenshot({ path: `${outDir}/17_route_walk.png` });
console.log("walk", JSON.stringify(await page.evaluate(() => window.mars.firstPerson.at)));
console.log(logs.slice(0, 6).join("\n"));
await browser.close();
