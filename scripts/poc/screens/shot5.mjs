import { chromium } from "playwright-core";
const [url, outDir] = process.argv.slice(2);
const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--use-angle=metal", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
const logs = [];
page.on("pageerror", (e) => logs.push(`pageerror: ${e.message}`));
page.on("console", (m) => { if (m.type() === "error") logs.push(m.text()); });
await page.goto(url);
await page.waitForSelector("button[data-action=street]", { timeout: 30000 });
console.log("street button:", await page.textContent("button[data-action=street]"));
await page.waitForTimeout(4000);
const fp = () => page.evaluate(() => { const f = window.mars.firstPerson; return f && { mode: f.mode, stop: f.stopId, lat: +f.at.lat.toFixed(6), lon: +f.at.lon.toFixed(6), h: +f.at.height.toFixed(2), az: Math.round(f.az), arrows: f.arrows?.children.length }; });
await page.selectOption(".stop-select", "m2020_site1_drive52");
await page.click("button[data-action=street]");
await page.waitForTimeout(3000);
console.log("pano", JSON.stringify(await fp()));
const arrows = await page.evaluate(() => window.mars.firstPerson.arrows.children.map((a) => a.userData.stopId));
console.log("arrow targets", arrows.join(" "));
await page.evaluate(() => window.mars.look(0, -25));
await page.waitForTimeout(800);
await page.screenshot({ path: `${outDir}/13_pano_arrows.png` });
await page.keyboard.press("KeyW");
await page.waitForTimeout(3000);
console.log("after W", JSON.stringify(await fp()));
await page.evaluate(() => window.mars.look(0, 25));
await page.waitForTimeout(800);
await page.screenshot({ path: `${outDir}/14_next_stop.png` });
await page.keyboard.press("KeyF");
await page.waitForTimeout(6000);
console.log("walk start", JSON.stringify(await fp()));
await page.keyboard.down("KeyW");
await page.waitForTimeout(5000);
await page.keyboard.up("KeyW");
await page.waitForTimeout(6000);
console.log("walk after 5 s", JSON.stringify(await fp()));
await page.screenshot({ path: `${outDir}/15_walk.png` });
await page.keyboard.press("KeyE");
await page.waitForTimeout(3000);
console.log("after E", JSON.stringify(await fp()));
await page.keyboard.press("Escape");
await page.waitForTimeout(1000);
console.log("after Esc", JSON.stringify(await fp()));
console.log(logs.slice(0, 8).join("\n"));
await browser.close();
